"""Convert Codex's creatures/roster.json into the Species "Roster" child module (Codex contract, Run 1).

Usage (project root):  python tools/roster_to_luau.py creatures/roster.json src/core/shared/SpeciesRoster.luau
Then sync it as ReplicatedStorage.CC_Core.Species.Roster (ModuleScript child of Species) and checksum.
Expected JSON: a list of {"id": "snake_case", "name": str, "region": int (0 = weather-linked), "rarity": one of
Common/Uncommon/Rare/Epic/Legendary (omit for guardians), "ecology": str, "kind": "creature"|"guardian",
optional "replaces": "stub_..." (retires that stub; saved profiles holding the stub id are remapped on load),
optional "guardian"/"pup" links, optional "weather"}. Unknown keys are ignored. Read-only on creatures/.
"""
import json
import re
import sys

RARITIES = {"Common", "Uncommon", "Rare", "Epic", "Legendary"}
KEYS = ("id", "name", "region", "rarity", "ecology", "kind", "replaces", "guardian", "pup", "weather")


def lua(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(src, dst):
    data = json.load(open(src, encoding="utf-8"))
    out, errors = [], []
    for i, e in enumerate(data):
        sid = e.get("id", "")
        if not re.fullmatch(r"[a-z][a-z0-9_]*", sid):
            errors.append(f"entry {i}: bad id {sid!r}")
            continue
        kind = e.get("kind", "creature")
        if kind == "creature" and e.get("rarity") not in RARITIES:
            errors.append(f"{sid}: bad rarity {e.get('rarity')!r}")
            continue
        fields = ", ".join(f"{k} = {lua(e[k])}" for k in KEYS if k in e and e[k] is not None)
        out.append(f"\t{{ {fields} }},")
    if errors:
        print("\n".join(errors))
        sys.exit(1)
    body = "-- Roster (generated by tools/roster_to_luau.py from creatures/roster.json; do not edit by hand)\nreturn {\n" + "\n".join(out) + "\n}\n"
    open(dst, "w", encoding="utf-8").write(body)
    print(f"{len(out)} species -> {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
